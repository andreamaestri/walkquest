#!/usr/bin/env node
/**
 * Generates the Material 3 Expressive colour tokens for WalkQuest.
 *
 *   npm run theme            # regenerate with the default seed
 *   SEED=#1b6b4f npm run theme
 *
 * Output: walkquest/static/css/m3e/color.generated.css (hex values, light + dark).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const SEED = process.env.SEED || '#127C80'; // Cornish sea teal
const OUT = new URL('walkquest/static/css/m3e/color.generated.css', 'file://' + process.cwd() + '/').pathname;

function tokens(isDark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0, '2025');
  const colors = new MaterialDynamicColors();
  const all = [...colors.allColors, colors.shadow(), colors.scrim(), colors.surfaceTint()];
  const seen = new Set();
  const lines = [];
  for (const color of all) {
    const name = color.name.replace(/_/g, '-').toLowerCase();
    if (seen.has(name)) continue;
    seen.add(name);
    lines.push(`  --md-sys-color-${name}: ${hexFromArgb(color.getArgb(scheme))};`);
  }
  // surface-variant is deprecated in M3 but still referenced by older components.
  if (!seen.has('surface-variant')) {
    lines.push(`  --md-sys-color-surface-variant: ${hexFromArgb(colors.surfaceContainerHighest().getArgb(scheme))};`);
  }
  return lines.join('\n');
}

const light = tokens(false);
const dark = tokens(true);

const css = `/* Generated by scripts/generate-m3-theme.mjs — do not edit by hand.
   Seed: ${SEED} · SchemeTonalSpot · spec 2025 */

:root,
:root[data-theme="light"] {
  color-scheme: light;
${light}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${dark}
}

/* First paint before JavaScript applies data-theme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${dark.replace(/^/gm, '  ')}
  }
}
`;

writeFileSync(OUT, css);
console.log(`Wrote ${OUT} (seed ${SEED})`);
